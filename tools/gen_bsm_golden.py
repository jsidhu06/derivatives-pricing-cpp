#!/usr/bin/env python3
"""Generate tests/golden/bsm_reference.inc from the Python reference library.

Usage (from the repo root, with the Python package importable):

    python tools/gen_bsm_golden.py > tests/golden/bsm_reference.inc

Each row records the inputs of a European vanilla valuation plus the present
value, analytical Greeks and NUMERICAL (bump-and-revalue, default bumps)
Greeks produced by ``derivatives_pricing``. The C++ suite replays every row
through ``dp::OptionValuation`` and requires agreement to ~1e-12 (analytic)
and ~1e-8 (numerical).
"""

from __future__ import annotations

import datetime as dt
import itertools
import sys

import derivatives_pricing as dp

PRICING_DATE = dt.datetime(2025, 1, 1)
NUM = dp.GreekCalculationMethod.NUMERICAL


def row(label, *, spot, strike, rate, div_yield, vol, maturity_days, option_type,
        div_amount=0.0, div_day=0):
    maturity = PRICING_DATE + dt.timedelta(days=maturity_days)
    r_curve = dp.DiscountCurve.flat(rate)
    q_curve = dp.DiscountCurve.flat(div_yield) if div_yield != 0.0 else None
    md = dp.MarketData(PRICING_DATE, r_curve, currency="USD")
    divs = [(PRICING_DATE + dt.timedelta(days=div_day), div_amount)] if div_amount else None
    ud = dp.UnderlyingData(
        initial_value=spot, volatility=vol, market_data=md,
        dividend_curve=q_curve, discrete_dividends=divs,
    )
    spec = dp.VanillaSpec(
        option_type=option_type, exercise_type=dp.ExerciseType.EUROPEAN,
        strike=strike, maturity=maturity,
    )
    ov = dp.OptionValuation(ud, spec, dp.PricingMethod.BSM)
    values = [
        ov.present_value(),
        ov.delta(), ov.gamma(), ov.vega(), ov.theta(), ov.rho(),
        ov.delta(greek_calc_method=NUM), ov.gamma(greek_calc_method=NUM),
        ov.vega(greek_calc_method=NUM), ov.theta(greek_calc_method=NUM),
        ov.rho(greek_calc_method=NUM),
    ]
    is_call = "true" if option_type is dp.OptionType.CALL else "false"
    nums = ", ".join(repr(float(v)) for v in values)
    return (f'    {{"{label}", {spot!r}, {strike!r}, {rate!r}, {div_yield!r}, {vol!r}, '
            f'{maturity_days}, {div_amount!r}, {div_day}, {is_call}, {nums}}},')


def main() -> None:
    rows = []
    grid = itertools.product(
        [80.0, 100.0, 120.0],          # spot
        [0.0, 0.05],                   # rate
        [0.0, 0.03],                   # dividend yield
        [0.2, 0.5],                    # vol
        [30, 365, 730],                # maturity days
        [dp.OptionType.CALL, dp.OptionType.PUT],
    )
    for spot, rate, q, vol, days, ot in grid:
        label = f"S{spot:g}_r{rate:g}_q{q:g}_v{vol:g}_T{days}_{ot.name[0]}"
        rows.append(row(label, spot=spot, strike=100.0, rate=rate, div_yield=q, vol=vol,
                        maturity_days=days, option_type=ot))
    # Discrete cash dividends (escrowed-dividend spot adjustment).
    for ot in (dp.OptionType.CALL, dp.OptionType.PUT):
        for amount, day in ((1.0, 180), (2.5, 30), (0.75, 364)):
            rows.append(row(f"div{amount:g}_d{day}_{ot.name[0]}", spot=100.0, strike=100.0,
                            rate=0.05, div_yield=0.0, vol=0.2, maturity_days=365,
                            option_type=ot, div_amount=amount, div_day=day))
        rows.append(row(f"div_and_yield_{ot.name[0]}", spot=105.0, strike=100.0, rate=0.04,
                        div_yield=0.02, vol=0.3, maturity_days=500, option_type=ot,
                        div_amount=1.5, div_day=100))

    out = sys.stdout
    out.write("// Generated by tools/gen_bsm_golden.py from derivatives_pricing "
              f"{dp.__version__}. Do not edit.\n")
    out.write("// Columns: label, spot, strike, rate, div_yield, vol, maturity_days, "
              "div_amount, div_day, is_call,\n")
    out.write("//          pv, delta, gamma, vega, theta, rho, "
              "delta_num, gamma_num, vega_num, theta_num, rho_num\n")
    out.write("// NOLINTBEGIN\n")
    out.write("inline constexpr BsmGoldenRow kBsmGolden[] = {\n")
    out.write("\n".join(rows))
    out.write("\n};\n// NOLINTEND\n")


if __name__ == "__main__":
    main()
