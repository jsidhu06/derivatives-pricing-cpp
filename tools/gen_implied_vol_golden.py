#!/usr/bin/env python3
"""Generate tests/golden/implied_vol_reference.inc from the Python reference library.

Usage (repo root):

    .venv-goldenref/bin/python tools/gen_implied_vol_golden.py > tests/golden/implied_vol_reference.inc

Each row prices a vanilla at `true_vol`, then records the Python solver's
implied vol for that target (starting from the valuation's 0.2 vol). The
C++ solver must recover the same volatility. Maturities are whole days so
the chrono and pandas date handling coincide exactly.
"""

from __future__ import annotations

import datetime as dt
import itertools
import sys

import derivatives_pricing as dp

PRICING_DATE = dt.datetime(2025, 1, 1)
SOLVER = {"NR": dp.ImpliedVolMethod.NEWTON_RAPHSON, "BI": dp.ImpliedVolMethod.BISECTION,
          "BR": dp.ImpliedVolMethod.BRENTQ}
ENGINE = {"BSM": dp.PricingMethod.BSM, "TREE": dp.PricingMethod.BINOMIAL,
          "PDE": dp.PricingMethod.PDE_FD}
TREE_STEPS = 200
PDE_SPOT_STEPS = 80
PDE_TIME_STEPS = 100


def valuation(engine, *, spot, strike, rate, div_yield, div_amount, div_day, vol,
              maturity_days, option_type, exercise):
    maturity = PRICING_DATE + dt.timedelta(days=maturity_days)
    md = dp.MarketData(PRICING_DATE, dp.DiscountCurve.flat(rate), currency="USD")
    q_curve = dp.DiscountCurve.flat(div_yield) if div_yield != 0.0 else None
    divs = [(PRICING_DATE + dt.timedelta(days=div_day), div_amount)] if div_amount else None
    ud = dp.UnderlyingData(initial_value=spot, volatility=vol, market_data=md,
                           dividend_curve=q_curve, discrete_dividends=divs)
    spec = dp.VanillaSpec(option_type=option_type, exercise_type=exercise,
                          strike=strike, maturity=maturity)
    params = None
    if engine == "TREE":
        params = dp.BinomialParams(num_steps=TREE_STEPS)
    elif engine == "PDE":
        params = dp.PDEParams(spot_steps=PDE_SPOT_STEPS, time_steps=PDE_TIME_STEPS)
    return dp.OptionValuation(ud, spec, ENGINE[engine], params=params)


def row(label, engine, solver, *, spot=100.0, strike=100.0, rate=0.05, div_yield=0.0,
        div_amount=0.0, div_day=0, true_vol, maturity_days=365, option_type, exercise):
    kwargs = dict(spot=spot, strike=strike, rate=rate, div_yield=div_yield,
                  div_amount=div_amount, div_day=div_day, maturity_days=maturity_days,
                  option_type=option_type, exercise=exercise)
    target = valuation(engine, vol=true_vol, **kwargs).present_value()
    result = dp.implied_volatility(target, valuation(engine, vol=0.2, **kwargs),
                                   method=SOLVER[solver], max_iter=200)
    if not result.converged:
        raise RuntimeError(f"{label}: Python solver did not converge")
    flags = ["true" if option_type is dp.OptionType.CALL else "false",
             "true" if exercise is dp.ExerciseType.AMERICAN else "false"]
    return (f'    {{"{label}", "{engine}", "{solver}", {spot!r}, {strike!r}, {rate!r}, '
            f'{div_yield!r}, {div_amount!r}, {div_day}, {true_vol!r}, {maturity_days}, '
            f'{", ".join(flags)}, {float(target)!r}, {float(result.implied_vol)!r}}},')


def main() -> None:
    C, P = dp.OptionType.CALL, dp.OptionType.PUT
    EU, AM = dp.ExerciseType.EUROPEAN, dp.ExerciseType.AMERICAN
    rows = []

    # BSM: every solver across moneyness and vol level.
    for solver, strike, vol, ot in itertools.product(
            ["NR", "BI", "BR"], [80.0, 100.0, 125.0], [0.08, 0.3, 1.2], [C, P]):
        rows.append(row(f"BSM_{solver}_K{strike:g}_v{vol:g}_{ot.name[0]}", "BSM", solver,
                        strike=strike, true_vol=vol, option_type=ot, exercise=EU))
    # BSM with a dividend yield and with a cash dividend (spot-adjusted bounds).
    for solver, ot in itertools.product(["NR", "BR"], [C, P]):
        rows.append(row(f"BSM_{solver}_q_{ot.name[0]}", "BSM", solver, div_yield=0.03,
                        true_vol=0.25, option_type=ot, exercise=EU))
        rows.append(row(f"BSM_{solver}_cash_{ot.name[0]}", "BSM", solver, spot=52.0,
                        strike=50.0, div_amount=0.5, div_day=90, true_vol=0.35,
                        option_type=ot, exercise=EU))

    # Binomial and PDE: European and American, with and without dividends.
    for engine, solver, ot, ex in itertools.product(
            ["TREE", "PDE"], ["NR", "BI", "BR"], [C, P], [EU, AM]):
        q = 0.02 if ot is C else 0.0
        rows.append(row(f"{engine}_{solver}_{ot.name[0]}_{ex.name[:2]}", engine, solver,
                        div_yield=q, true_vol=0.3, option_type=ot, exercise=ex))
    for engine, ot in itertools.product(["TREE", "PDE"], [C, P]):
        rows.append(row(f"{engine}_BR_K90_v0.6_{ot.name[0]}_AM", engine, "BR", strike=90.0,
                        true_vol=0.6, option_type=ot, exercise=AM))

    print(f"// Generated by tools/gen_implied_vol_golden.py from derivatives_pricing "
          f"{dp.__version__}. Do not edit.")
    print("// Columns: label, engine, solver, spot, strike, rate, div_yield, div_amount, div_day,")
    print("//          true_vol, maturity_days, is_call, is_american, target_price, implied_vol")
    print(f"// Engine settings: binomial num_steps={TREE_STEPS}; PDE spot_steps={PDE_SPOT_STEPS},"
          f" time_steps={PDE_TIME_STEPS} (other params default).")
    print("// NOLINTBEGIN")
    print("inline constexpr ImpliedVolGoldenRow kImpliedVolGolden[] = {")
    for r in rows:
        print(r)
    print("};")
    print("// NOLINTEND")
    print(f"// {len(rows)} rows", file=sys.stderr)


if __name__ == "__main__":
    main()
